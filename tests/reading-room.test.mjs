import fs from "node:fs";
import assert from "node:assert/strict";
import {generateSite} from "../studio/generator.mjs";
const text=path=>fs.readFileSync(path,"utf8");
const articles=JSON.parse(text("content/articles.json")).articles;
const page=text("discover/index.html"),home=text("index.html"),js=text("assets/discover.js"),reading=text("assets/reading.js"),css=text("assets/discover.css"),styles=text("assets/reading-room.css");
const generated=generateSite(articles);
assert.equal(generated["discover/index.html"],page,"The Discover page must match the generator");
assert(page.includes('aria-label="Story shuffle"'),"Missing story shuffle");
assert(page.includes('id="quiz-stage"'),"Missing knowledge challenge");
assert(page.includes('id="saved-stories"')&&page.includes('id="recent-stories"'),"Reading shelves missing");
assert(page.includes('data-topic-filter="all"'),"Topic filtering not discoverable");
assert.equal((page.match(/data-discover-item /g)||[]).length,articles.filter(a=>a.status!=="draft").length,"Every visible article must appear in Discover");
assert(page.includes('assets/discover.js')&&page.includes('assets/discover.css'),"Discover assets missing");
assert(page.includes('assets/reading.js'),"Global reading feature missing");
assert(home.includes('class="reading-room-teaser"'),"Home missing discover teaser");
assert(home.includes('data-surprise'),"Homepage surprise button missing");
assert(home.includes('href="./discover/"'),"Homepage discover route missing");
assert(home.includes('>Discover</a>'),"Header discover navigation missing");
assert(home.includes('href="./assets/reading-room.css"'),"Reader styles not loaded");
for(const a of articles.filter(a=>a.status!=="draft")){
 const route="article/"+a.id+"/index.html",article=text(route);
 assert(article.includes('data-story-id="'+a.id+'"'),"Article history ID missing on "+route);
 assert(article.includes('class="reading-next-grid"'),"Related story recommendations missing on "+route);
 assert(article.includes('assets/reading.js'),"Reader controls missing on "+route);
 assert(article.includes('href="../../discover/"'),"Article lacks Reading Room link: "+route);
}
assert(text("assets/site.js").includes('data.saveStory=storyId')||text("assets/site.js").includes("save.dataset.saveStory=storyId"),"Article save button missing");
assert(text("assets/site.js").includes("focus.dataset.readingFocus"),"Focus mode button missing");
assert(text("assets/site.js").includes("size.dataset.textSize"),"Text sizing button missing");
assert(reading.includes("civora-reading-list-v1")&&reading.includes("civora-reading-history-v1"),"Reader storage keys missing");
assert(reading.includes("try{localStorage")||reading.includes("try{const data=JSON.parse(localStorage"),"Reader storage must fail safely");
assert(!/\bfetch\s*\(/.test(reading)&&!/\bfetch\s*\(/.test(js),"Reading controls should not transmit personal reading history");
assert(js.includes("reading.getSaved()")&&js.includes("reading.getRecent()"),"Reading Room not connected to shelves");
assert(js.includes("quizIndex")&&js.includes("questions"),"Challenge implementation missing");
assert(css.includes("@media(max-width:760px)"),"Discover lacks mobile layout");
assert(styles.includes("prefers-reduced-motion:reduce"),"Reader animation does not respect reduced motion");
assert(text("privacy/index.html").includes("recently opened article identifiers"),"Privacy notice missing reading-history disclosure");
const future={...articles[0],id:"future-story-in-room",title:"A future published news story",status:"published",publishedAt:"2026-11-09",kind:"news"};
const next=generateSite([...articles,future]);
assert(next["discover/index.html"].includes(future.title),"New articles aren't surfaced automatically");
assert(next["index.html"].includes(future.title),"New articles aren't surfaced on homepage");
assert(next["article/"+future.id+"/index.html"].includes('class="reading-next-grid"'),"New articles lack recommendations");
const sample=next["discover/index.html"];
assert(!sample.includes("EDITORIAL SAMPLE"),"Demonstration cards must not remain");
assert(text("discover/index.html").includes('id="discover-topic-select"'),"Topic selector missing from Reading Room");
console.log("PASS Reading Room: story shuffle, all stories, reading shelves, quiz, article tools, privacy, responsive layout, and new publication.");
