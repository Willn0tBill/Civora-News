import fs from "node:fs";
import assert from "node:assert/strict";
import worker from "../backend/cloudflare/worker.mjs";
const read=p=>fs.readFileSync(p,"utf8");
const html=read("studio/secure/index.html");
const app=read("studio/secure/studio.mjs");
const config=read("studio/secure/config.mjs");
const server=read("backend/cloudflare/worker.mjs");
assert(html.includes('id="email"')&&html.includes('id="password"'),"Secure login lacks email/password fields.");
assert(html.includes('id="reset-password"'),"Missing password reset.");
assert(html.includes('name="robots" content="noindex,nofollow"'),"Admin login must not be indexed.");
assert(!html.includes('id="token"')&&!html.includes("personal-access-tokens"),"Public login still asks for a GitHub token.");
assert(app.includes("signInWithEmailAndPassword")&&app.includes("browserLocalPersistence"),"Login/persistent session missing.");
assert(app.includes("onAuthStateChanged")&&app.includes("sendPasswordResetEmail"),"Session recovery or password reset missing.");
assert(app.includes('backend("publish"')&&app.includes('backend("load"'),"Publishing must use Worker backend.");
assert(!app.includes("api.github.com"),"Admin browser must not talk to GitHub directly.");
assert(config.includes('apiKey: ""')&&config.includes('publisherUrl = ""'),"The initial config must fail closed until setup.");
assert(!config.includes("GITHUB_TOKEN")&&!config.includes("service_role"),"Public config contains sensitive credential names.");
assert(server.includes('crypto.subtle.verify')&&server.includes('importKey("jwk"'),"JWT signature check missing.");
assert(server.includes('FIREBASE_PROJECT_ID')&&server.includes("STAFF_UIDS"),"Server-side identity/role checks missing.");
assert(server.includes("GITHUB_TOKEN")&&server.includes("ALLOWED_ORIGIN"),"Secret and origin controls missing.");
assert(server.includes('expectedSha')&&server.includes('generateSite'),"Publishing missing optimistic conflict check or HTML build.");
assert(server.includes("The website has changed."),"Stale layout protection missing.");
// The Worker must reject unauthenticated callers before any GitHub API requests.
const origin="https://willn0tbill.github.io";
const denied=await worker.fetch(new Request("https://example.workers.dev",{method:"POST",headers:{Origin:"https://evil.example"}}),{});
assert.equal(denied.status,403,"Untrusted origin should be denied.");
const preflight=await worker.fetch(new Request("https://example.workers.dev",{method:"OPTIONS",headers:{Origin:origin}}),{});
assert.equal(preflight.status,204,"Expected CORS preflight handling.");
const notConfigured=await worker.fetch(new Request("https://example.workers.dev",{method:"POST",headers:{Origin:origin}}),{});
assert.equal(notConfigured.status,503,"Unconfigured Worker must fail closed.");
const anon=await worker.fetch(new Request("https://example.workers.dev",{method:"POST",headers:{Origin:origin}}),{GITHUB_TOKEN:"placeholder",STAFF_UIDS:"uid",FIREBASE_PROJECT_ID:"project"}); 
assert.equal(anon.status,401,"Anonymous publishing request must be rejected.");
