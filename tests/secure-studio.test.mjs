import fs from "node:fs";
import assert from "node:assert/strict";
import worker from "../backend/cloudflare/worker.mjs";
const read=p=>fs.readFileSync(p,"utf8");
const html=read("studio/secure/index.html"),admin=read("studio/index.html"),app=read("studio/newsroom.js");
assert(html.includes('http-equiv="refresh"')&&html.includes('url=../'),"Old Firebase sign-in should redirect to Supabase Studio");
assert(!html.includes('id="password"'),"Abandoned login must not collect passwords");
assert(admin.includes('id="loginEmail"')&&app.includes("signInWithPassword"),"PPW-style login missing");
assert(app.includes('db.from("civora_editors")'),"Dedicated Civora role checks missing");
const bad=await worker.fetch(new Request("https://example.workers.dev",{method:"POST",headers:{Origin:"https://evil.example"}}),{});
assert.equal(bad.status,403,"Legacy Worker accepted untrusted origin");
const empty=await worker.fetch(new Request("https://example.workers.dev",{method:"POST",headers:{Origin:"https://civoranews.org"}}),{});
assert.equal(empty.status,503,"Legacy backend should fail closed without secrets");
console.log("PASS old Firebase login retired and Supabase newsroom role checks configured.");